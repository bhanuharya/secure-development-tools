def png_size(data: bytes) -> tuple[int, int]:
    """(width, height) in pixels from a PNG header."""
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        raise ValueError("logo must be a PNG")
    return int.from_bytes(data[16:20], "big"), int.from_bytes(data[20:24], "big")


def logo_run(rid: str, size: tuple[int, int], width_inches: float, pic_id: int) -> str:
    """An inline picture, width fixed, height by aspect ratio."""
    cx = int(width_inches * 914400)
    cy = int(cx * size[1] / size[0])
    a, pic = "http://schemas.openxmlformats.org/drawingml/2006/main", "http://schemas.openxmlformats.org/drawingml/2006/picture"
    return (f'<w:r><w:drawing><wp:inline distT="0" distB="0" distL="0" distR="0"><wp:extent cx="{cx}" cy="{cy}"/>'
            f'<wp:docPr id="{pic_id}" name="Logo {pic_id}"/><wp:cNvGraphicFramePr><a:graphicFrameLocks xmlns:a="{a}" '
            f'noChangeAspect="1"/></wp:cNvGraphicFramePr><a:graphic xmlns:a="{a}"><a:graphicData uri="{pic}">'
            f'<pic:pic xmlns:pic="{pic}"><pic:nvPicPr><pic:cNvPr id="{pic_id}" name="logo.png"/><pic:cNvPicPr/></pic:nvPicPr>'
            f'<pic:blipFill><a:blip r:embed="{rid}"/><a:stretch><a:fillRect/></a:stretch></pic:blipFill>'
            f'<pic:spPr><a:xfrm><a:off x="0" y="0"/><a:ext cx="{cx}" cy="{cy}"/></a:xfrm>'
            f'<a:prstGeom prst="rect"><a:avLst/></a:prstGeom></pic:spPr></pic:pic></a:graphicData></a:graphic>'
            f'</wp:inline></w:drawing></w:r>')


