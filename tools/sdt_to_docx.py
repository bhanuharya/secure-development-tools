# Fixed wording per review outcome, so every recommendation reads the same way.
REVIEW_OUTCOME = {
    "likely_false_positive": ("False positive - can be marked Safe", "Before marking Safe, confirm",
                              "Record in SonarQube"),
    "likely_true_positive": ("Real issue - fix required", "Confirm impact", "Fix"),
    "needs_context": ("Manual check required", "Check", "Then"),
}
AI_VERDICT_TEXT = REVIEW_OUTCOME  # verdicts this report understands


def apply_triage(groups: list[Group], triage: dict) -> int:
    """Attach advisory AI notes to their occurrences (by rule, file, line); how many matched."""
    notes = {(r.get("rule"), r.get("path"), r.get("line")): r for r in triage.get("results", [])
             if r.get("verdict") in AI_VERDICT_TEXT}
    matched = 0
    for group in groups:
        for occurrence in group.occurrences:
            note = notes.get((group.rule, occurrence.path, occurrence.line))
            if note:
                occurrence.ai = note
                matched += 1
    return matched


def review_lines(note: dict) -> list[tuple[str, str]]:
    """(label, text) rows of one review recommendation, in a fixed order."""
    outcome, check_label, action_label = REVIEW_OUTCOME[note["verdict"]]
    rows = [("Assessment", f"{outcome} (certainty: {str(note.get('confidence', 'low')).title()})")]
    for label_text, key in (("Evidence", "reason"), (check_label, "check"), (action_label, "suggested_fix")):
        if note.get(key):
            rows.append((label_text, note[key]))
    return rows


def ai_line(note: dict) -> str:
    """The same recommendation on one line (for occurrences listed without code)."""
    return "; ".join(f"{name}: {text}" for name, text in review_lines(note))


def consolidate(rows: list[DependencyRow]) -> list[DependencyRow]:
    """One row per (package, version, manifest); advisories without a known package stay separate."""
    merged: "OrderedDict[tuple, DependencyRow]" = OrderedDict()
    for row in rows:
        key = (row.package, row.installed, row.manifest) if row.package else (id(row),)
        if key not in merged:
            merged[key] = row
            continue
        target = merged[key]
        for advisory, severity in row.advisories.items():
            target.advisories[advisory] = _worse(target.advisories.get(advisory, "Info"), severity)
        target.fixed.update(row.fixed)
    return list(merged.values())


# ------------------------------------------------------------------ secret groups
FIREBASE_FILE = re.compile(r"(google-services\.json|GoogleService-Info\.plist|firebase_options\.dart|firebase\.json)$", re.I)
GOOGLE_KEY = re.compile(r"(?i)gcp-api-key|google.?api.?key")


@dataclass
class SecretGroup:
    """All reports of one kind of secret in one file (every build flavour, commit and scanner)."""
    kind: str
    path: str
    count: int = 0
    lines: set = field(default_factory=set)
    commits: set = field(default_factory=set)
    places: set = field(default_factory=set)  # "Current code" / "Git history only"
    statuses: set = field(default_factory=set)
    severity: str = "Info"
    client_key: bool = False  # a Firebase/Google client key: restrict it, do not rotate

    @property
    def where(self) -> str:
        if {"Current code", "Git history only"} <= self.places:
            return "Code and history"
        return next(iter(self.places)) if self.places else "Unknown"

    @property
    def open(self) -> bool:
        return bool(self.statuses & set(OPEN_STATES)) or not self.statuses

    @property
    def action(self) -> str:
        if self.client_key:
            return "Restrict the key (API + Android/iOS app restrictions); rotation not required"
        if "Current code" in self.places:
            return "Rotate, then remove from the code"
        return "Rotate; record the rotation"


def group_secrets(rows: list[SecretRow]) -> list[SecretGroup]:
    """One row per (kind, file): gitleaks history hits, current hits and SonarQube's own reports
    of the same file collapse together; client keys are marked, not treated as leaked secrets."""
    groups: "OrderedDict[tuple, SecretGroup]" = OrderedDict()
    for r in rows:
        kind = "gcp-api-key" if GOOGLE_KEY.search(r.kind) else r.kind
        group = groups.setdefault((kind, r.path), SecretGroup(kind, r.path))
        group.count += 1
        if r.line:
            group.lines.add(r.line)
        if r.commit:
            group.commits.add(r.commit)
        group.places.add(r.where)
        group.statuses.add(r.status)
        group.severity = r.severity if group.count == 1 else _worse(group.severity, r.severity)
        group.client_key = kind == "gcp-api-key" and bool(FIREBASE_FILE.search(r.path or ""))
    return sorted(groups.values(), key=lambda g: (g.client_key, "Current code" not in g.places, g.path, g.kind))


def _short(values: set, limit: int, width: int = 0) -> str:
    items = sorted(values, key=lambda v: (isinstance(v, str), v))
    text = ", ".join(str(v)[:width] if width else str(v) for v in items[:limit])
    return (text + (f" (+{len(items) - limit})" if len(items) > limit else "")) if items else "-"


