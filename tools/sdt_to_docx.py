def run(text: str, bold: bool = False, size: int = 20, color: str = "", mono: bool = False) -> str:
    props = ('<w:rFonts w:ascii="Consolas" w:hAnsi="Consolas"/>' if mono else "") + \
            ("<w:b/>" if bold else '<w:b w:val="0"/>') + (f'<w:color w:val="{color}"/>' if color else "") + \
            f'<w:sz w:val="{size}"/>'
    # Every piece of report text passes here: redact, so no credential can reach a developer's copy.
    return f'<w:r><w:rPr>{props}</w:rPr><w:t xml:space="preserve">{escape(sdt_advisory.redact(text))}</w:t></w:r>'


def para(runs: str, before: int = 40, after: int = 80, align: str = "") -> str:
    # pPr children are schema-ordered: spacing precedes jc.
    jc = f'<w:jc w:val="{align}"/>' if align else ""
    return f'<w:p><w:pPr><w:spacing w:before="{before}" w:after="{after}"/>{jc}</w:pPr>{runs}</w:p>'


def heading(text: str, level: int) -> str:
    return f'<w:p><w:pPr><w:pStyle w:val="Heading{level}"/></w:pPr><w:r><w:t xml:space="preserve">{escape(text)}</w:t></w:r></w:p>'


