def trow(cells: str, header: bool = False) -> str:
    """A row that never splits across pages; header rows repeat on every page."""
    return f'<w:tr><w:trPr><w:cantSplit/>{"<w:tblHeader/>" if header else ""}</w:trPr>{cells}</w:tr>'


def data_table(columns: list[tuple[str, int]], rows: list[list], severity_col: int | None = None,
               total: list | None = None, advisory_cols: tuple = ()) -> str:
    """Header row (repeated per page), data rows (severity cells coloured), optional TOTAL row.

    A row value may be a (text, raw_runs) tuple to put a hyperlink in the cell.
    """
    out = [trow("".join(tcell(name, width, fill=BRAND_COLOR, bold=True, color="FFFFFF") for name, width in columns),
                header=True)]
    for row in rows:
        cells = []
        for index, (value, (_, width)) in enumerate(zip(row, columns)):
            if isinstance(value, tuple):
                cells.append(tcell(value[1], width, raw=True))
            else:
                fill = SEVERITY_FILL.get(str(value), "") if index == severity_col else ""
                cells.append(tcell(value, width, fill=fill))
        out.append(trow("".join(cells)))
    if total:
        out.append(trow("".join(tcell(v, w, fill="F3F4F6", bold=True) for v, (_, w) in zip(total, columns))))
    return table([w for _, w in columns], out)


