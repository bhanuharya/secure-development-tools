def from_findings(doc: dict, src_root: Path | None = None) -> dict:
    """The four categories from an SDT findings.json (richer for secrets and dependencies)."""
    groups: "OrderedDict[str, Group]" = OrderedDict()
    secrets, config = [], []
    packages: "OrderedDict[tuple, DependencyRow]" = OrderedDict()
    for f in doc.get("findings", []):
        if f.get("suppression"):
            continue  # covered by an approved exception, e.g. a reviewed false positive
        rule = f.get("rule") or {}
        rule_id = str(rule.get("id") or "unknown")
        adapter = str((f.get("scanner") or {}).get("adapter") or "sdt")
        what = str(f.get("category") or "")
        severity = SDT_SEVERITY.get(str((f.get("severity") or {}).get("canonical", "")).lower(), "Medium")
        location = f.get("location") or {}
        artifact = f.get("artifact") or {}
        path, line = str(location.get("path") or ""), int(location.get("startLine") or 0)
        message = str(f.get("message") or "").split("\n")[0][:300]
        if what == "secret":
            commit = str((f.get("metadata") or {}).get("commit") or "")
            evidence = str((f.get("evidence") or {}).get("text") or "")
            secrets.append(SecretRow(rule_id, path, line, commit[:12], _where(src_root, path, line, evidence), severity))
        elif artifact.get("package"):
            key = (artifact["package"], artifact.get("installedVersion", ""), artifact.get("target", path))
            row = packages.setdefault(key, DependencyRow(*key))
            row.advisories[rule_id] = _worse(row.advisories.get(rule_id, "Info"), severity)
            fixed = artifact.get("fixedVersion") or (f.get("remediation") or {}).get("fixedVersion")
            if fixed:
                row.fixed[rule_id] = str(fixed)
            state = str((f.get("reachability") or {}).get("state") or "")
            row.reachable = {"reachable": "Yes", "unreachable": "No"}.get(state, row.reachable)
        elif what == "misconfiguration" or adapter.startswith("trivy"):
            config.append(ConfigRow(rule_id, path or str(artifact.get("target") or ""), line, message, severity))
        else:
            key = f"{adapter}:{rule_id}"
            if key not in groups:
                guidance = str((f.get("remediation") or {}).get("guidance") or "")
                groups[key] = Group(key, str(rule.get("name") or rule_id), "Finding", severity,
                                    [message] if message else [],
                                    [s.strip() for s in re.split(r"(?<=[.!?])\s+", guidance) if s.strip()])
            group = groups[key]
            group.severity = _worse(group.severity, severity)
            group.occurrences.append(Occurrence(path, line, message, "Not reviewed", ""))
    return {"code": list(groups.values()), "secret": secrets, "dependency": list(packages.values()), "config": config}


PLACEHOLDER = re.compile(r"your|example|change-?me|placeholder|dummy|replace|todo|xxx|\*\*\*|^<|^\$\{|^\{\{|^[\"']{0,2}$",
                         re.IGNORECASE)


def _where(src_root: Path | None, path: str, line: int, evidence: str = "") -> str:
    """Whether a secret is still in the checkout, or only in git history.

    gitleaks scans history, so its line number is where the secret was first committed.
    With the redacted evidence ('key = "[REDACTED]"') the answer is whether that line still
    exists anywhere in the current file with a real-looking value (not a placeholder such as
    "your-api-key"); without it, only whether the line number exists.
    """
    if src_root is None or not path:
        return "Unknown"
    target = src_root / path
    try:
        lines = target.read_text(encoding="utf-8", errors="replace").splitlines() if target.is_file() else []
    except OSError:
        return "Unknown"
    if not lines:
        return "Git history only"
    if "[REDACTED]" in evidence:
        parts = [re.escape(part.strip()) for part in evidence.split("[REDACTED]")]
        pattern = re.compile(r"(\S+)".join(parts))
        # The line may still be there with the secret replaced by a placeholder (an example
        # file cleaned up after the leak): then the secret itself is only in history.
        values = [m.groups() for m in map(pattern.search, lines) if m]
        return "Current code" if any(not all(PLACEHOLDER.search(v) for v in found) for found in values) \
            else "Git history only"
    return "Current code" if 0 < line <= len(lines) else "Git history only"


def merge(sonar: dict, sdt: dict | None) -> dict:
    """Code from SonarQube; secrets, dependencies and configuration from SDT (with Sonar's
    review status where the same file and line match). A secret that both gitleaks and
    Sonar's own secret rules report on one line is listed once."""
    if not sdt:
        merged = dict(sonar)
    else:
        merged = {"code": sonar["code"], "secret": list(sdt["secret"]), "dependency": sdt["dependency"],
                  "config": sdt["config"] or sonar["config"]}
        status = {(r.path, r.line): r.status for r in sonar["secret"]}
        for row in merged["secret"]:
            row.status = status.get((row.path, row.line), row.status)
        merged["secret"] += [r for r in sonar["secret"] if (r.path, r.line) not in {(s.path, s.line) for s in sdt["secret"]}]
    seen, secrets = set(), []
    for row in merged["secret"]:
        key = (row.path, row.line) if row.path else (row.kind, row.commit, id(row))
        if key not in seen:
            seen.add(key)
            secrets.append(row)
    merged["secret"] = sorted(secrets, key=lambda r: (r.where != "Current code", r.path, r.line))
    merged["dependency"] = sorted(merged["dependency"],
                                  key=lambda r: (SEVERITY_ORDER.index(r.severity), r.package, r.installed))
    merged["code"] = sorted(merged["code"], key=lambda g: (SEVERITY_ORDER.index(g.severity), -len(g.occurrences), g.rule))
    return merged


# ------------------------------------------------------------------------ helpers
def snippet(src_root: Path | None, occurrence: Occurrence) -> list[str]:
    """The flagged line with a little context, prefixed with its location, or []."""
    if not src_root or not occurrence.path or occurrence.line < 1:
        return []
    root = src_root.resolve()
    path = (root / occurrence.path).resolve()
    if root not in path.parents or not path.is_file():
        return []
    try:
        lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    except OSError:
        return []
    start, end = max(1, occurrence.line - SNIPPET_CONTEXT), min(len(lines), occurrence.line + SNIPPET_CONTEXT)
    out = [f"// {occurrence.path}:{occurrence.line}"]
    for number in range(start, end + 1):
        marker = ">" if number == occurrence.line else " "
        out.append(f"{marker}{number:>5}  {sdt_advisory.redact(lines[number - 1].rstrip())[:160]}")
    return out


CITED_LINES = re.compile(r"\blines?\s+(\d+)(?:\s*(?:-|–|to|and)\s*(\d+))?", re.I)
MERGE_GAP = 12  # flagged and cited lines this close share one excerpt, so the code reads continuously


def cited_lines(note: dict | None, near: int, reach: int = 200) -> list[int]:
    """Line numbers an advisory cites as evidence ("line 92", "lines 93-106") near the finding."""
    if not note:
        return []
    found = set()
    for key in ("reason", "check", "suggested_fix"):
        for first, last in CITED_LINES.findall(str(note.get(key) or "")):
            a = int(first)
            b = int(last) if last else a
            if b < a or b - a > 20:
                b = a
            found.update(n for n in range(a, b + 1) if abs(n - near) <= reach)
    return sorted(found)


def snippet_blocks(src_root: Path | None, path: str, flagged: list[int], max_block: int = 60,
                   cited: list[int] = ()) -> list[list[str]]:
    """Code excerpts covering every flagged line of one file (marked ">") and every line the
    advisory cites as evidence (marked "*"). Nearby lines share one excerpt, so each shows once.
    Likely secret values are redacted: the report must never carry a credential."""
    if not src_root or not path:
        return []
    root = src_root.resolve()
    target = (root / path).resolve()
    if root not in target.parents or not target.is_file():
        return []
    try:
        lines = target.read_text(encoding="utf-8", errors="replace").splitlines()
    except OSError:
        return []
    hits_all = {n for n in flagged if 1 <= n <= len(lines)}
    cited_all = {n for n in cited if 1 <= n <= len(lines)} - hits_all
    marks = sorted(hits_all | cited_all)
    blocks, windows = [], []
    for n in marks:
        start, end = max(1, n - SNIPPET_CONTEXT), min(len(lines), n + SNIPPET_CONTEXT)
        if windows and start <= windows[-1][1] + MERGE_GAP and end - windows[-1][0] < max_block:
            windows[-1][1] = end
        else:
            windows.append([start, end])
    for start, end in windows:
        hits = [n for n in sorted(hits_all) if start <= n <= end]
        also = [n for n in sorted(cited_all) if start <= n <= end]
        header = f"// {path}:{', '.join(map(str, hits))}" + (f"  (* cited: {', '.join(map(str, also))})" if also else "")
        block = [header]
        for k in range(start, end + 1):
            marker = ">" if k in hits_all else "*" if k in cited_all else " "
            block.append(f"{marker}{k:>5}  {sdt_advisory.redact(lines[k - 1].rstrip())[:160]}")
        blocks.append(block)
    return blocks


def status_summary(occurrences: list[Occurrence]) -> str:
    counts = Counter(o.status for o in occurrences)
    return counts.most_common(1)[0][0] if len(counts) == 1 else ", ".join(f"{s} {n}" for s, n in counts.most_common())


def assignee_summary(occurrences: list[Occurrence]) -> str:
    names = sorted({o.assignee for o in occurrences if o.assignee})
    unassigned = sum(1 for o in occurrences if not o.assignee)
    if not names:
        return "Not assigned"
    return ", ".join(names) + (f" ({unassigned} not assigned)" if unassigned else "")


def plural(n: int, word: str) -> str:
    if n == 1:
        return f"{n} {word}"
    return f"{n} {word[:-1]}ies" if word.endswith("y") and word[-2:-1] not in "aeiou" else f"{n} {word}s"


