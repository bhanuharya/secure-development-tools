# ------------------------------------------------------------------ categorising
# Trivy advisories are dependencies; its other ids (DS-, KSV-, AVD-) are configuration checks.
DEPENDENCY_RULE = re.compile(r"^(external_sdt-trivy[^:]*:sdt-trivy[^-]*(-fs)?-(CVE|GHSA|GO|PYSEC|RUSTSEC|OSV|DSA|RHSA|ELSA)-"
                             r"|sdt:vulnerable-dependency)")
SECRET_RULE = re.compile(r"^(sdt:secret|secrets:|external_sdt-gitleaks)")
CONFIG_RULE = re.compile(r"^external_sdt-trivy")
EXTERNAL_ID = re.compile(r"^external_sdt-[a-z-]+?:sdt-(?:gitleaks|trivy-fs|trivy)-(?P<id>.+)-[0-9a-f]{16}$")
HISTORY_SECRET = re.compile(r"Secret \((?P<kind>[^)]+)\) in git history: (?P<path>[^\s:]+)(?::(?P<line>\d+))?"
                            r"(?: at commit (?P<commit>[0-9a-f]+))?")
DEPENDENCY_MESSAGE = re.compile(r"^(?P<id>\S+) in (?P<package>\S+) (?P<installed>\S+?)(?:: upgrade to (?P<fixed>[^.]+))?\.")


def category(rule_key: str) -> str:
    """'secret', 'dependency', 'config' or 'code' for a Sonar rule key."""
    if SECRET_RULE.search(rule_key):
        return "secret"
    if DEPENDENCY_RULE.search(rule_key):
        return "dependency"
    if CONFIG_RULE.search(rule_key):
        return "config"
    return "code"


def external_id(rule_key: str) -> str:
    """'external_sdt-gitleaks:sdt-gitleaks-gcp-api-key-<hash>' -> 'gcp-api-key'."""
    match = EXTERNAL_ID.match(rule_key)
    return match.group("id") if match else rule_key.split(":", 1)[-1]


def _version(text: str) -> tuple:
    return tuple(int(n) for n in re.findall(r"\d+", text)[:4])


def upgrade_to(row: "DependencyRow") -> str:
    """The lowest version that fixes every advisory of this package, or "" when unknown.

    Each advisory lists one fixed version per maintained branch; the useful one is the
    lowest at or above the installed version. The package needs the highest of those.
    """
    installed, targets = _version(row.installed), []
    for fixed in row.fixed.values():
        candidates = sorted((_version(v), v.strip()) for v in fixed.split(",") if _version(v))
        above = [c for c in candidates if c[0] >= installed] or candidates
        if above:
            targets.append(above[0])
    return max(targets)[1] if targets else ""


def _worse(a: str, b: str) -> str:
    return min(a, b, key=SEVERITY_ORDER.index)


# ------------------------------------------------------------------- sonar source
def from_sonar(sonar: Sonar, project_key: str, branch: str, pull_request: str) -> tuple[str, dict]:
    """Project name and the four categories as SonarQube reports them."""
    scope = {"branch": branch, "pullRequest": pull_request}
    component = sonar.get("/api/components/show", component=project_key, **scope)["component"]
    hotspots = sonar.paged("/api/hotspots/search", "hotspots", projectKey=project_key, **scope)
    issues = sonar.paged("/api/issues/search", "issues", componentKeys=project_key, types="VULNERABILITY",
                         resolved="false", **scope)
    groups: "OrderedDict[str, Group]" = OrderedDict()
    rules: dict[str, dict] = {}
    found = {"code": [], "secret": [], "dependency": [], "config": []}

    def rule(rule_key: str) -> dict:
        if rule_key not in rules:
            rules[rule_key] = sonar.get("/api/rules/show", key=rule_key).get("rule", {})
        return rules[rule_key]

    def code(rule_key: str, kind: str, severity: str, occurrence: Occurrence) -> None:
        if rule_key not in groups:
            risk, fixes = rule_texts(rule(rule_key))
            groups[rule_key] = Group(rule_key, rule(rule_key).get("name", rule_key), kind, severity, risk, fixes)
        group = groups[rule_key]
        group.severity = _worse(group.severity, severity)
        group.occurrences.append(occurrence)

    base = sonar.url
    scope_query = "".join(f"&{k}={urllib.parse.quote(v)}" for k, v in scope.items() if v)

    def link(item: dict, hotspot: bool) -> str:
        if hotspot:
            return f"{base}/security_hotspots?id={urllib.parse.quote(project_key)}{scope_query}&hotspots={item['key']}"
        return f"{base}/project/issues?id={urllib.parse.quote(project_key)}{scope_query}&open={item['key']}"

    entries = [(h["ruleKey"], "Security Hotspot",
                {"HIGH": "High", "MEDIUM": "Medium", "LOW": "Low"}.get(h.get("vulnerabilityProbability"), "Medium"),
                HOTSPOT_STATUS.get((h.get("status", ""), h.get("resolution", "")), h.get("status", "").title()), h)
               for h in hotspots]
    entries += [(i["rule"], "Vulnerability", SONAR_SEVERITY.get(i.get("severity", ""), "Medium"),
                 ISSUE_STATUS.get(i.get("issueStatus") or i.get("status", ""), i.get("status", "").title()), i)
                for i in issues]
    for rule_key, kind, severity, status, item in entries:
        path, line = _path(item.get("component", "")), item.get("line") or 0
        message = clean_message(item.get("message", ""))
        what = category(rule_key)
        if what == "code":
            code(rule_key, kind, severity, Occurrence(path, line, message, status, item.get("assignee", ""),
                                                      link=link(item, kind == "Security Hotspot") if "key" in item else ""))
        elif what == "secret":
            history = HISTORY_SECRET.search(message)
            if history:
                found["secret"].append(SecretRow(history.group("kind"), history.group("path"),
                                                 int(history.group("line") or 0), history.group("commit") or "",
                                                 "Git history only", severity, status))
            else:
                kind_name = external_id(rule_key) if rule_key.startswith("external_") else \
                    ("secret" if rule_key.startswith("sdt:") else rule(rule_key).get("name", rule_key))
                found["secret"].append(SecretRow(kind_name, path, line, "", "Current code", severity, status))
        elif what == "dependency":
            parsed = DEPENDENCY_MESSAGE.match(message)
            if parsed:
                row = DependencyRow(parsed.group("package"), parsed.group("installed"), path)
                row.advisories[parsed.group("id")] = severity
                if parsed.group("fixed"):
                    row.fixed[parsed.group("id")] = parsed.group("fixed").strip()
                row.reachable = "No" if rule_key.endswith("unreachable") else "Yes/unknown"
            else:  # an external per-advisory issue: the package is only in its text
                row = DependencyRow("", "", path)
                row.advisories[external_id(rule_key)] = severity
            row.status = status
            found["dependency"].append(row)
        else:
            found["config"].append(ConfigRow(external_id(rule_key), path, line, message, severity, status))
    found["code"] = list(groups.values())
    return component.get("name", project_key), found


