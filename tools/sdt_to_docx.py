# ------------------------------------------------------------------- sonar source
class Sonar:
    def __init__(self, url: str, token: str):
        self.url, self.token = url.rstrip("/"), token

    def get(self, path: str, **params) -> dict:
        query = urllib.parse.urlencode({k: v for k, v in params.items() if v not in (None, "")})
        request = urllib.request.Request(f"{self.url}{path}?{query}")
        request.add_header("Authorization", "Basic " + base64.b64encode(f"{self.token}:".encode()).decode())
        with urllib.request.urlopen(request, timeout=60) as response:
            return json.load(response)

    def paged(self, path: str, key: str, **params) -> list[dict]:
        items, page = [], 1
        while True:
            data = self.get(path, p=page, ps=500, **params)
            items += data.get(key, [])
            total = (data.get("paging") or {}).get("total", data.get("total", 0))
            if page * 500 >= total or not data.get(key):
                return items
            page += 1


def _html_paragraphs(fragment: str, prefer_list: bool = False) -> list[str]:
    """Plain-text paragraphs (or, with prefer_list, list items) from a rule's HTML description.

    Headings and code examples are dropped: they are structure in Sonar's rule page,
    not sentences a reader can act on.
    """
    fragment = re.sub(r"<(h\d|pre)[^>]*>.*?</\1>", " ", fragment or "", flags=re.I | re.S)
    items = re.findall(r"<li[^>]*>(.*?)</li>", fragment, flags=re.I | re.S)
    parts = items if prefer_list and items else re.split(r"</?(?:p|li|ul|ol|div)[^>]*>", fragment, flags=re.I)
    texts = [" ".join(html.unescape(re.sub(r"<[^>]+>", " ", part)).split()) for part in parts]
    return [text for text in texts if len(text) > 2 and not text.endswith(":") and not REFERENCE.match(text)
            and not DOC_TITLE.match(text)]


def rule_texts(rule: dict) -> tuple[list[str], list[str]]:
    """(risk, fixes) from a rule: description sections when Sonar has them, else split on 'How to fix'."""
    sections = {s.get("key"): s.get("content", "") for s in rule.get("descriptionSections") or []}
    if sections:
        risk = _html_paragraphs(sections.get("root_cause", "") or sections.get("introduction", ""))
        fixes = _html_paragraphs(sections.get("how_to_fix", ""), prefer_list=True)
        return risk[:4], fixes[:6]
    desc = rule.get("htmlDesc") or ""
    fix_heading = re.search(r"<h2[^>]*>\s*How to fix it\s*</h2>", desc, re.I)
    head, tail = (desc[:fix_heading.start()], desc[fix_heading.end():]) if fix_heading else (desc, "")
    risk = [p for p in _html_paragraphs(head) if not p.lower().startswith(("standards", "references", "opengrep rule"))]
    fixes = _html_paragraphs(tail.split("<h2")[0], prefer_list=True) if tail else []
    return risk[:4], fixes[:6]


def clean_message(message: str) -> str:
    """One readable line: advisory markdown headings and code ticks removed."""
    text = re.sub(r"#{1,6}\s*(Summary|Description|Details|Impact|Overview)\s*", "", message or "")
    return " ".join(text.replace("`", "").split())


def _path(component_key: str) -> str:
    """'project:lib/a.dart' -> 'lib/a.dart'; a project-level key has no path."""
    return component_key.split(":", 1)[1] if ":" in component_key else ""


