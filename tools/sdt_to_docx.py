    parts.append(internal_link("3. Dependencies & Configuration (Trivy)", "sec_dependencies"))
    parts.append(internal_link("Review Notes", "sec_notes"))
    parts.append('<w:p><w:r><w:fldChar w:fldCharType="end"/></w:r></w:p>')
