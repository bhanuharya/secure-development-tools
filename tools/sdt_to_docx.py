def bitbucket_base(repository: str, commit: str, host: str = "https://bitbucket.org") -> str:
    """Source browser base for a workspace/repo at a commit, or "" when either is unknown."""
    if "/" not in repository or not commit:
        return ""
    return f"{host.rstrip('/')}/{repository.strip('/')}/src/{commit}"


def code_url(base: str, path: str, lines: list[int], commit: str = "") -> str:
    """A Bitbucket link to a file at the scanned commit (or `commit`), highlighting its line(s)."""
    if not base or not path:
        return ""
    if commit:
        base = base.rsplit("/src/", 1)[0] + f"/src/{commit}"
    marked = sorted({n for n in lines if n})
    anchor = "" if not marked else f"#lines-{marked[0]}" + (f":{marked[-1]}" if marked[-1] != marked[0] else "")
    return f"{base}/{urllib.parse.quote(path)}{anchor}"


