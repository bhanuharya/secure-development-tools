@dataclass
class Group:
    """One code-security rule and where it fired."""
    rule: str
    name: str
    kind: str  # "Security Hotspot", "Vulnerability" or "Finding"
    severity: str
    risk: list[str] = field(default_factory=list)
    fixes: list[str] = field(default_factory=list)
